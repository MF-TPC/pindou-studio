function getPalette(id) {
  const src = PALETTES[id];
  if (!src) return null;
  return { ...src, colors: src.colors.map(function(c) { return { ...c }; }) };
}

function getPaletteIds() { return Object.keys(PALETTES); }

function getPaletteMeta() {
  return Object.entries(PALETTES).map(function(e) {
    var id = e[0], p = e[1];
    return { id: id, name: p.name, beadSize: p.beadSize, boardSize: p.boardSize, colorCount: p.colors.length };
  });
}

function getColorsByGroup(paletteId) {
  var palette = PALETTES[paletteId];
  if (!palette) return {};
  var groups = {};
  for (var i = 0; i < palette.colors.length; i++) {
    var c = palette.colors[i];
    var g = c.group || '?';
    if (!groups[g]) groups[g] = { label: GROUP_META[g] ? GROUP_META[g].label : g, order: GROUP_META[g] ? GROUP_META[g].order : 99, colors: [] };
    groups[g].colors.push(c);
  }
  var entries = Object.entries(groups);
  entries.sort(function(a, b) { return a[1].order - b[1].order; });
  return Object.fromEntries(entries);
}
